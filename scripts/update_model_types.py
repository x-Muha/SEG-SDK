#!/usr/bin/env python
"""Regenerate the model-id ``Literal`` types from the live SovereignEG catalog.

The typed hints (``ChatModel``, ``ImageModel``, ``EmbeddingModel``, ``ModerationModel``) only
drive editor autocomplete; every ``model`` parameter also accepts any ``str``. Keep them in step
with ``GET /v1/models`` by running:

    SEG_API_KEY=sk-... [SEG_BASE_URL=https://sovereigneg.com/v1] python scripts/update_model_types.py

The key is read from the environment only; nothing in this script stores it.
"""

from __future__ import annotations

import os
import sys
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TYPES = ROOT / "src" / "seg" / "types"
sys.path.insert(0, str(ROOT / "src"))

from seg import SEG  # noqa: E402
from seg.types import Model  # noqa: E402

# `/v1/moderations` is not in the catalog; the gateway runs a single built-in keyword scorer.
MODERATION_MODELS = ["sovereigneg-basic-keyword-check"]

HEADER = """# Generated by scripts/update_model_types.py from GET /v1/models; do not edit by hand.
"""

MODERATION_HEADER = """# Written by scripts/update_model_types.py from its MODERATION_MODELS constant; the moderation
# scorer is not part of GET /v1/models, so update that constant when the gateway adds one.
"""

DOC = '''"""Model ids served by the SovereignEG {modality} endpoint.

This list only drives editor autocomplete; the ``model`` parameter also accepts any
``str``, so ids added to the catalog after this release still work. Regenerate it with
``scripts/update_model_types.py``.
"""
'''


def fetch_catalog() -> list[Model]:
    if not os.environ.get("SEG_API_KEY"):
        sys.exit("SEG_API_KEY is not set")
    # The client reads SEG_API_KEY and SEG_BASE_URL itself.
    return list(SEG().models.list())


def render(name: str, ids: list[str], *, modality: str, future_import: bool, header: str = HEADER) -> str:
    lines: list[str] = [header]
    if future_import:
        lines.append("from __future__ import annotations\n\n")
    lines.append("from typing_extensions import Literal, TypeAlias\n\n")
    lines.append(f'__all__ = ["{name}"]\n\n')
    one_line = f"{name}: TypeAlias = Literal[{', '.join(json.dumps(i) for i in ids)}]"
    if len(one_line) <= 120:  # ruff's line length, so short lists come out already formatted
        lines.append(one_line + "\n")
    else:
        lines.append(f"{name}: TypeAlias = Literal[\n")
        for model_id in ids:
            lines.append(f"    {json.dumps(model_id)},\n")
        lines.append("]\n")
    lines.append(DOC.format(modality=modality))
    return "".join(lines)


def ids_for(models: list[Model], modality: str) -> list[str]:
    # Only advertise models the gateway accepts today; deprecated or retired entries stay out.
    ids = {m.id for m in models if m.modality == modality and m.status in (None, "live")}
    return sorted(ids, key=str.lower)


def write(path: Path, content: str) -> None:
    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT)}")


def main() -> None:
    models = fetch_catalog()
    chat = ids_for(models, "chat")
    image = ids_for(models, "image")
    embed = ids_for(models, "embed")
    if not (chat and image and embed):
        sys.exit("catalog is missing a modality; refusing to write empty lists")

    write(TYPES / "shared" / "chat_model.py", render("ChatModel", chat, modality="chat", future_import=False))
    write(
        TYPES / "shared_params" / "chat_model.py",
        render("ChatModel", chat, modality="chat", future_import=True),
    )
    write(TYPES / "image_model.py", render("ImageModel", image, modality="image", future_import=False))
    write(TYPES / "embedding_model.py", render("EmbeddingModel", embed, modality="embedding", future_import=False))
    write(
        TYPES / "moderation_model.py",
        render(
            "ModerationModel",
            MODERATION_MODELS,
            modality="moderation",
            future_import=False,
            header=MODERATION_HEADER,
        ),
    )


if __name__ == "__main__":
    main()
