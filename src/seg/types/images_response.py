from typing import List, Union, Optional
from typing_extensions import Literal

from .image import Image
from .._models import BaseModel

__all__ = ["ImagesResponse", "Usage", "UsageInputTokensDetails", "UsageOutputTokensDetails"]


class UsageInputTokensDetails(BaseModel):
    """The input tokens detailed information for the image generation."""

    image_tokens: int
    """The number of image tokens in the input prompt."""

    text_tokens: int
    """The number of text tokens in the input prompt."""


class UsageOutputTokensDetails(BaseModel):
    """The output token details for the image generation."""

    image_tokens: int
    """The number of image output tokens generated by the model."""

    text_tokens: int
    """The number of text output tokens generated by the model."""


class Usage(BaseModel):
    """Usage for the image generation.

    The SovereignEG gateway always reports `cost` (the amount charged, in EGP);
    token counts are present only when the serving provider reports them.
    """

    cost: Optional[float] = None
    """The amount charged for this generation, in EGP."""

    input_tokens: Optional[int] = None
    """The number of tokens (images and text) in the input prompt."""

    input_tokens_details: Optional[UsageInputTokensDetails] = None
    """The input tokens detailed information for the image generation."""

    output_tokens: Optional[int] = None
    """The number of output tokens generated by the model."""

    total_tokens: Optional[int] = None
    """The total number of tokens (images and text) used for the image generation."""

    output_tokens_details: Optional[UsageOutputTokensDetails] = None
    """The output token details for the image generation."""


class ImagesResponse(BaseModel):
    """The response from the image generation endpoint."""

    created: int
    """The Unix timestamp (in seconds) of when the image was created."""

    background: Optional[Literal["transparent", "opaque"]] = None
    """The background parameter used for the image generation.

    Either `transparent` or `opaque`.
    """

    data: Optional[List[Image]] = None
    """The list of generated images."""

    output_format: Optional[Literal["png", "webp", "jpeg"]] = None
    """The output format of the image generation. Either `png`, `webp`, or `jpeg`."""

    quality: Optional[str] = None
    """The quality requested for the image generation, as echoed by the gateway."""

    runtime_ms: Optional[int] = None
    """Wall-clock time the provider spent generating the image, in milliseconds."""

    size: Union[str, Literal["1024x1024", "1024x1536", "1536x1024"], None] = None
    """The image dimensions as a `WIDTHxHEIGHT` string, for example `1536x864`."""

    usage: Optional[Usage] = None
    """Cost and, when available, token usage for the image generation."""
